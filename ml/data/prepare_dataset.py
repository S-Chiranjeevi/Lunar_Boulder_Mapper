"""Convert curated lunar boulder datasets into leakage-free YOLO box format."""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path
from typing import Any

from .bickel_policy import ExcludedTile, filter_curated_records
from .bouldering import BOULDERING_LICENSE, load_bouldering_lunar_tiles
from .label_studio import load_label_studio_export
from .schema import TileRecord
from .split import SplitName, assign_group_splits, verify_no_group_leakage


def _format_yolo_yaml(output_dir: Path) -> str:
    resolved = output_dir.resolve().as_posix()
    return "\n".join(
        [
            "# MoonSafe curated lunar boulder detection dataset (screening prototype).",
            "# Generated by ml/data/prepare_dataset.py; do not assume training validation.",
            f"path: {resolved}",
            "train: images/train",
            "val: images/val",
            "test: images/test",
            "nc: 1",
            "names:",
            "  0: boulder",
            "",
        ]
    )


def prepare_yolo_dataset(
    *,
    output_dir: str | Path,
    bouldering_dir: str | Path | None = None,
    bouldering_allowlist: str | Path | None = None,
    label_studio_json: str | Path | None = None,
    label_studio_images_dir: str | Path | None = None,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    seed: int = 42,
    copy_images: bool = False,
    include_reviewed_bickel: bool = False,
    extra_records: list[TileRecord] | None = None,
) -> dict[str, Any]:
    """Assemble curated lunar tiles, enforce Bickel policy, group-split, and write YOLO labels."""
    out_root = Path(output_dir)
    if out_root.exists() and any(out_root.iterdir()):
        raise FileExistsError(
            f"Output directory is not empty: {out_root}. Choose a fresh directory to avoid stale files."
        )
    out_root.mkdir(parents=True, exist_ok=True)

    raw_records: list[TileRecord] = []
    excluded_records: list[ExcludedTile] = []

    if bouldering_dir is not None:
        boulder_tiles, boulder_excluded, _ = load_bouldering_lunar_tiles(
            bouldering_dir,
            allowlist_path=bouldering_allowlist,
        )
        raw_records.extend(boulder_tiles)
        excluded_records.extend(boulder_excluded)

    if label_studio_json is not None:
        raw_records.extend(
            load_label_studio_export(
                label_studio_json,
                images_dir=label_studio_images_dir,
            )
        )

    if extra_records:
        raw_records.extend(extra_records)

    accepted_records, policy_excluded = filter_curated_records(
        raw_records,
        include_reviewed_bickel=include_reviewed_bickel,
    )
    excluded_records.extend(policy_excluded)

    splits = assign_group_splits(
        accepted_records,
        train_ratio=train_ratio,
        val_ratio=val_ratio,
        test_ratio=test_ratio,
        seed=seed,
    )
    verify_no_group_leakage(splits)

    for split_name in ("train", "val", "test"):
        (out_root / "images" / split_name).mkdir(parents=True, exist_ok=True)
        (out_root / "labels" / split_name).mkdir(parents=True, exist_ok=True)

    provenance_rows: list[dict[str, Any]] = []
    split_counts: dict[str, dict[str, int]] = {}
    licenses_seen: set[str] = set()
    sources_seen: set[str] = set()
    seen_image_ids: set[str] = set()

    for split_name in ("train", "val", "test"):
        split_tiles = splits[split_name]  # type: ignore[index]
        tile_boxes_total = 0

        for record in split_tiles:
            if record.image_id in seen_image_ids:
                raise ValueError(
                    f"Duplicate image_id '{record.image_id}' encountered across curated sources"
                )
            seen_image_ids.add(record.image_id)

            yolo_lines: list[str] = []
            source_formats: set[str] = set()
            for box in record.boxes:
                cls_id, xc, yc, bw, bh = box.to_yolo_normalized(record.width_px, record.height_px)
                yolo_lines.append(f"{cls_id} {xc:.6f} {yc:.6f} {bw:.6f} {bh:.6f}")
                source_formats.add(box.source_format)

            label_file = out_root / "labels" / split_name / f"{record.image_id}.txt"
            label_file.write_text(
                ("\n".join(yolo_lines) + "\n") if yolo_lines else "",
                encoding="utf-8",
            )

            copied_image_rel: str | None = None
            if copy_images and record.image_path is not None and record.image_path.is_file():
                target_image = (
                    out_root / "images" / split_name / f"{record.image_id}{record.image_path.suffix.lower()}"
                )
                shutil.copy2(record.image_path, target_image)
                copied_image_rel = target_image.relative_to(out_root).as_posix()

            tile_boxes_total += len(yolo_lines)
            licenses_seen.add(record.license)
            sources_seen.add(record.label_source)

            provenance_rows.append(
                {
                    "image_id": record.image_id,
                    "source_observation_id": record.source_observation_id,
                    "site_id": record.site_id,
                    "split": split_name,
                    "split_group_key": record.split_group_key,
                    "width_px": record.width_px,
                    "height_px": record.height_px,
                    "gsd_x_m_per_px": record.gsd_x_m_per_px,
                    "gsd_y_m_per_px": record.gsd_y_m_per_px,
                    "coordinate_units": record.coordinate_units,
                    "label_units": "normalized_xywh",
                    "box_count": len(yolo_lines),
                    "source_formats": sorted(source_formats),
                    "label_source": record.label_source,
                    "task_type": record.task_type,
                    "reviewed_for_standalone_boulder": record.reviewed_for_standalone_boulder,
                    "license": record.license,
                    "provenance_notes": record.provenance_notes,
                    "source_image_path": str(record.image_path) if record.image_path else None,
                    "copied_image_rel": copied_image_rel,
                    "label_rel": label_file.relative_to(out_root).as_posix(),
                }
            )

        split_counts[split_name] = {
            "tile_count": len(split_tiles),
            "box_count": tile_boxes_total,
            "unique_groups": len({tile.split_group_key for tile in split_tiles}),
            "unique_observations": len({tile.source_observation_id for tile in split_tiles}),
        }

    (out_root / "dataset.yaml").write_text(_format_yolo_yaml(out_root), encoding="utf-8")

    (out_root / "provenance_manifest.jsonl").write_text(
        "".join(json.dumps(row) + "\n" for row in provenance_rows),
        encoding="utf-8",
    )

    (out_root / "excluded_manifest.jsonl").write_text(
        "".join(
            json.dumps(
                {
                    "image_id": item.image_id,
                    "source_observation_id": item.source_observation_id,
                    "label_source": item.label_source,
                    "reason_code": item.reason_code,
                    "detail": item.detail,
                }
            )
            + "\n"
            for item in excluded_records
        ),
        encoding="utf-8",
    )

    summary = {
        "total_accepted_tiles": len(accepted_records),
        "total_excluded_tiles": len(excluded_records),
        "total_boxes": sum(item["box_count"] for item in split_counts.values()),
        "split_ratios_requested": {"train": train_ratio, "val": val_ratio, "test": test_ratio},
        "seed": seed,
        "zero_group_leakage_verified": True,
        "splits": split_counts,
        "label_sources": sorted(sources_seen),
        "licenses": sorted(licenses_seen),
        "bouldering_license_reference": BOULDERING_LICENSE,
        "model_trained": False,
    }
    (out_root / "split_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n",
        encoding="utf-8",
    )
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Prepare MoonSafe curated lunar boulder labels in YOLO detection format."
    )
    parser.add_argument("--output-dir", type=Path, required=True, help="Output YOLO dataset folder.")
    parser.add_argument(
        "--bouldering-dir",
        type=Path,
        default=None,
        help="Optional extracted BOULDERING directory (Zenodo 14250874).",
    )
    parser.add_argument(
        "--bouldering-allowlist",
        type=Path,
        default=None,
        help="Optional newline/JSON list of verified lunar observation IDs in BOULDERING.",
    )
    parser.add_argument(
        "--label-studio-json",
        type=Path,
        default=None,
        help="Optional Label Studio JSON export of curated NAC tile annotations.",
    )
    parser.add_argument(
        "--label-studio-images-dir",
        type=Path,
        default=None,
        help="Optional directory holding local NAC tile images referenced by Label Studio.",
    )
    parser.add_argument("--train-ratio", type=float, default=0.7)
    parser.add_argument("--val-ratio", type=float, default=0.15)
    parser.add_argument("--test-ratio", type=float, default=0.15)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--copy-images",
        action="store_true",
        help="Copy source image files into output_dir/images/{train,val,test}/.",
    )
    parser.add_argument(
        "--include-reviewed-bickel",
        action="store_true",
        help=(
            "Include Bickel/rockfall records ONLY when explicitly marked "
            "reviewed_for_standalone_boulder=True."
        ),
    )
    args = parser.parse_args(argv)

    summary = prepare_yolo_dataset(
        output_dir=args.output_dir,
        bouldering_dir=args.bouldering_dir,
        bouldering_allowlist=args.bouldering_allowlist,
        label_studio_json=args.label_studio_json,
        label_studio_images_dir=args.label_studio_images_dir,
        train_ratio=args.train_ratio,
        val_ratio=args.val_ratio,
        test_ratio=args.test_ratio,
        seed=args.seed,
        copy_images=args.copy_images,
        include_reviewed_bickel=args.include_reviewed_bickel,
    )
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
